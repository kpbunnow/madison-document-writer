#!/usr/bin/env python3
"""Lossless table provenance; no state-code tokens become Madison ordinances.

Input is the division DOCX table extracted in XML row order. Review records are
explicit; parsing a dollar amount never constitutes approval of that amount.
Run from any directory; --check compares without writing.
"""

import argparse
from pathlib import Path
import json
import re

ROOT = Path(__file__).resolve().parent.parent
GRAMMAR = r"^(?:SPS)?\d+\.\d+(?:\([a-z0-9]+\))*(?:\d+\.(?:[a-z]\.)?|[a-z]\.)?$"
PREFIX = r"^(?:(?:M\.?G\.?O\.?|Sec\.?|Section|§)\s*)+"


def canonical(value):
    text = re.sub(PREFIX, "", str(value).strip(), flags=re.I)
    text = re.sub(r"\s+", "", text)
    text = re.sub(r"^sps", "SPS", text, flags=re.I)
    text = re.sub(r"\(([^)]+)\)", lambda m: "(" + m[1].lower() + ")", text)
    if re.search(r"\)\d+$", text):
        text += "."
    return text if re.fullmatch(GRAMMAR, text) else ""


def tiers(raw):
    values = [int(round(float(x.replace(",", "")) * 100)) for x in re.findall(r"\$([\d,]+(?:\.\d+)?)", raw)]
    if not values or re.search(r"per |/inch|/ton|\+ \$|to \$|\-\$|maximum|minimum", raw, re.I):
        return []
    if len(values) > 1 and not re.search(r"1st|first|2nd|second|3\+", raw, re.I):
        return []
    return [{"ordinal": n + 1, "amountCents": v, "openEnded": n == len(values) - 1} for n, v in enumerate(values)]


def regenerate():
    rows = json.loads((ROOT / "policy/sources/r30-schedule-table.json").read_text())
    reviews = json.loads((ROOT / "policy/sources/r30-deposit-reviews.json").read_text())
    entries, exclusions = [], []
    for row, (desc, column, raw) in enumerate(rows[1:], 1):
        # Stop before explanatory IBC/SPS cross-references, never tokenize them.
        head = re.split(r"\(see | and .*SPS|Wis\. Stats", column, flags=re.I)[0].strip()
        if column.strip() == "28.141(10)(a)—(c)":
            ordinances = ["28.141(10)(" + x + ")" for x in "abc"]
        elif column.strip() == "23.24(1) and (2)":
            ordinances = ["23.24(1)", "23.24(2)"]
        else:
            ordinances = [canonical(x) for x in re.findall(r"\d+\.\d+(?:\([A-Za-z0-9]+\))*(?:\d+\.?(?:[a-z]\.)?)?", head)]
        ordinances = list(dict.fromkeys(x for x in ordinances if x))
        if not ordinances:
            exclusions.append(
                {
                    "sourceRow": row,
                    "description": desc.strip(),
                    "ordinanceColumn": column.strip(),
                    "rawText": raw.strip(),
                    "reason": "State statute or non-Madison citation: not a Madison automatic deposit.",
                }
            )
        for ord_ in ordinances:
            text = raw.strip()
            if row == 474:  # Two charges, each $200, not two offense tiers.
                text = "$200"
            parsed = tiers(text)
            m = re.search(r"(\d+)\s*(yrs?\.?|years?|mos?\.?|months?)", raw, re.I)
            window = (
                {"years" if m[2].lower().startswith(("yr", "year")) else "months": int(m[1])}
                if m
                else "site"
                if re.search(r"at (?:the )?site", raw, re.I)
                else "none"
            )
            review = reviews.get(ord_, {})
            stale = ord_ in ("27.05(2)(s)", "29.21", "30.01(5)")
            entries.append(
                {
                    "id": "mgo-row-" + str(row) + "-" + ord_,
                    "sourceRow": row,
                    "ordinance": ord_,
                    "description": desc.strip(),
                    "tiers": parsed,
                    "window": window,
                    "countBasis": "citation",
                    "status": "manual-only" if stale or not parsed else "verified" if review else "unverified",
                    "source": {"subsection": "MGO 1.08(3)(a)", "codification": "Rev. 28, Update 3", "exported": "2026-09-14"},
                    "review": review or None,
                    "stale": stale,
                    "rawText": text,
                    "sourceDepositText": raw.strip(),
                    "ordinanceColumn": column.strip(),
                    "statute": column.strip()[len(head) :].strip(),
                    "effectiveDate": "2026-09-14",
                }
            )
    data = (
        ("/* Generated by reference/regenerate_deposits.py; retain table and review provenance. */\nconst DEPOSITS=")
        + json.dumps(entries, ensure_ascii=False, indent=2)
        + ";\n"
    )
    return data, exclusions


if __name__ == "__main__":
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    data, excluded = regenerate()
    paths = {"app/assets/deposits.js": data, "policy/sources/r30-schedule-exclusions.json": json.dumps(excluded, indent=2) + "\n"}
    for name, text in paths.items():
        if args.check:
            if (ROOT / name).read_text() != text:
                raise SystemExit("Schedule differs from division table/review provenance: " + name)
        else:
            (ROOT / name).write_text(text)
