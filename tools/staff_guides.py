"""Generate staff quick guides from reviewed manual sections; builds only check drift."""

import argparse
import json
import os
import re
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
STAFF = ROOT / "docs/staff"
TAG = re.compile(r"<!-- guide:([a-z0-9-]+):(start|end) -->")
NAME = re.compile(r"(?:[A-Z][A-Z0-9-]*-GUIDE|06-REPORTING)\.md")


def sections(text):
    found, active = {}, None
    for marker in re.finditer(r"<!--\s*guide:.*?-->", text, re.DOTALL):
        match = TAG.fullmatch(marker[0])
        if not match:
            raise ValueError("Malformed manual guide marker")
        key, edge = match.groups()
        if edge == "start":
            if active or key in found:
                raise ValueError("Nested or duplicate manual guide section: " + key)
            active = key, marker.end()
        else:
            if not active or active[0] != key:
                raise ValueError("Unmatched manual guide end: " + key)
            body = text[active[1] : marker.start()].strip()
            if not body:
                raise ValueError("Empty manual guide section: " + key)
            found[key], active = body, None
    if active:
        raise ValueError("Unclosed manual guide section: " + active[0])
    return found


def generate(staff=STAFF):
    staff = Path(staff)
    inputs = sections((staff / "PROGRAM-MANUAL.md").read_text(encoding="utf-8"))
    manifest = json.loads((staff / "guide-sections.json").read_text(encoding="utf-8"))
    if manifest.get("format") != "document-writer-staff-guides" or manifest.get("version") != 1:
        raise ValueError("Unsupported staff guide manifest")
    outputs = {}
    for guide in manifest["guides"]:
        name, keys = guide["file"], guide["sections"]
        if not NAME.fullmatch(name) or name in outputs or not keys or len(set(keys)) != len(keys):
            raise ValueError("Invalid or duplicate guide destination/sections")
        if (staff / name).is_symlink():
            raise ValueError("Staff guide destination is a symlink: " + name)
        body = "\n\n".join(inputs[key] for key in keys)
        outputs[name] = (
            guide["intro"].strip()
            + "\n\n<!-- Generated by tools/staff_guides.py from PROGRAM-MANUAL.md; edit its tagged sections. -->\n\n"
            + body
            + "\n"
        )
    if not outputs:
        raise ValueError("No staff guides declared")
    return outputs


def check(staff=STAFF):
    staff = Path(staff)
    outputs = generate(staff)
    stale = [name for name, text in outputs.items() if not (staff / name).is_file() or (staff / name).read_bytes() != text.encode("utf-8")]
    if stale:
        raise ValueError("Staff guides drift from manual; run python3 tools/staff_guides.py --write: " + ", ".join(stale))
    return len(outputs)


def write(staff=STAFF, replace=os.replace):
    """Validate/stage every guide first; restore prior bytes on a caught publication failure."""
    staff = Path(staff)
    outputs = generate(staff)
    previous = {name: (staff / name).read_bytes() if (staff / name).exists() else None for name in outputs}
    with tempfile.TemporaryDirectory(prefix=".guide-staging-", dir=staff) as folder:
        staging = Path(folder)
        for name, text in outputs.items():
            (staging / name).write_bytes(text.encode("utf-8"))
        changed = []
        try:
            for name in outputs:
                replace(staging / name, staff / name)
                changed.append(name)
        except BaseException:
            for name in changed:
                if previous[name] is None:
                    (staff / name).unlink(missing_ok=True)
                else:
                    (staging / name).write_bytes(previous[name])
                    os.replace(staging / name, staff / name)
            raise
    return check(staff)


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--write", action="store_true", help="explicitly regenerate maintained guide Markdown")
    args = parser.parse_args()
    print(str(write() if args.write else check()) + " staff guides agree with the manual")
