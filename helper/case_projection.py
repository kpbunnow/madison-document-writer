ISO = re.compile(
    r"([+-]\d{6}|\d{4})(?:-(\d{2})(?:-(\d{2}))?)?"
    r"(?:T(\d{2}):(\d{2})(?::(\d{2})(?:[.,](\d+))?)?)?"
    r"(Z|[+-]\d{2}:\d{2})?"
)


def date_ms(value):
    """Date.parse for ISO text: date-only is UTC, a date-time without offset is City local time."""
    if not isinstance(value, str):
        return None
    m = ISO.fullmatch(value.strip())
    if not m:
        return None
    year, month, day, hour, minute, second, fraction, zone = m.groups()
    if hour is None and zone is not None:
        return None
    try:
        instant = datetime.datetime(
            int(year), int(month or 1), int(day or 1), int(hour or 0), int(minute or 0), int(second or 0), int(((fraction or "") + "000")[:3]) * 1000
        )
    except ValueError:
        return None
    if zone == "Z":
        instant = instant.replace(tzinfo=datetime.timezone.utc)
    elif zone:
        sign = 1 if zone[0] == "+" else -1
        instant = instant.replace(tzinfo=datetime.timezone(sign * datetime.timedelta(hours=int(zone[1:3]), minutes=int(zone[4:6]))))
    elif hour is None:
        instant = instant.replace(tzinfo=datetime.timezone.utc)
    else:
        instant = instant.replace(tzinfo=CITY_ZONE)
    return (instant - datetime.datetime(1970, 1, 1, tzinfo=datetime.timezone.utc)) // datetime.timedelta(milliseconds=1)


def record_day(value):
    """shared.js recordDay: the City civil day of an instant; a plain date is returned unchanged."""
    if not truthy(value):
        return ""
    if re.fullmatch(r"\d{4}-\d{2}-\d{2}", jstr(value)):
        return jstr(value)
    ms = value if jtype(value) == "number" else date_ms(value)
    if ms is None or not math.isfinite(ms):
        return ""
    return (
        (datetime.datetime(1970, 1, 1, tzinfo=datetime.timezone.utc) + datetime.timedelta(milliseconds=ms)).astimezone(CITY_ZONE).strftime("%Y-%m-%d")
    )


def add_days(day, n):
    if not isinstance(day, str) or date_ms(day + "T12:00:00Z") is None:
        raise ValueError("Invalid date")
    return (datetime.date.fromisoformat(day[:10]) + datetime.timedelta(days=n)).isoformat()


def money_num(v):
    text = re.sub(r"[^0-9.]", "", "" if v is UNDEF or v is None else jstr(v))
    m = re.match(r"\d+\.?\d*|\.\d+", text)
    return float(m[0]) if m else None


def norm_parcel(p):
    digits = re.sub("[" + re.escape(JS_SPACE) + "-]", "", "" if p is UNDEF or p is None else jstr(p))
    return digits if re.fullmatch(r"[0-9]{12}", digits) else ""


def respondent_key(k):
    """citation_policy.js respondentKey."""
    p = get(k, "ownerAddressParsed")
    if truthy(get(p, "accepted")) and stringify(get(p, "acceptedLines")) == stringify(get(k, "ownerAddr")):
        return jor(get(p, "ownerKey"), "")
    lines = [trim(jstr(jor(x, ""))) for x in jor(get(k, "ownerAddr"), [])]
    lines = [x for x in lines if x]
    zipcode = re.search(r"(\d{5})(?:-\d{4})?" + S + "*$", lines[-1] if lines else "", re.A)
    street = next((x for x in reversed(lines[:-1]) if re.match(r"^(\d|P\.?" + S + r"*O\.?" + S + r"*BOX\b|POBOX\b)", x, re.I | re.A)), None)
    if not zipcode or not street:
        return ""
    words = resource_policy()["streetWords"]
    text = street.upper()
    text = re.sub(r"\bP\.?" + S + r"*O\.?" + S + r"*BOX\b", "PO BOX", text, flags=re.A)
    text = re.sub(r"\bPOBOX\b", "PO BOX", text, flags=re.A)
    text = re.sub("#" + S + "*", " UNIT ", text)
    text = re.sub(r"[^A-Z0-9 /-]", " ", text)
    text = trim(re.sub(S + "+", " ", text))
    text = " ".join(jor(words.get(w, UNDEF), w) for w in text.split(" "))
    return re.sub(r"\bUNIT UNIT\b", "UNIT", text, flags=re.A) + "|" + zipcode[1]


