def project(f, workspace=None):
    """summarize(f) for the reportable fields of a Reporting Index summary. The browser mirror is summarizeRecord in
    app/modules/case_projection.js; the phases below keep its statement order, so change both together."""
    workspace = workspace or Workspace(loaded=False)
    library, _ = tables()
    k = jor(get(f, "case"), {})
    documents, reinspections = replay_events(jor(get(f, "events"), []))
    name_of = roster_names(f, library)
    facts = Facts(documents)
    docs, live = facts.docs, facts.live
    status = case_status(k, facts)
    last_doc = facts.last_doc
    printed = jor(jand(last_doc, jand(get(last_doc, "frozen"), get(last_doc, "frozen", "case"))) if last_doc is not None else last_doc, k)
    visits = active_visits(reinspections, docs)
    no_of = item_numbers(docs)
    citations = citation_rows(live, name_of)
    snow_first = next((d for d in docs if snow_doc(d, k, workspace)), None) if snow_case(k) else None
    source = facts.notice if facts.notice is not None else snow_first
    ctx = {"docs": docs, "visits": visits, "no_of": no_of, "last_items": facts.last_items, "citations": citations}
    violations = [violation_row(ctx, it) for it in (get(source, "items") if source is not None and isinstance(get(source, "items"), list) else [])]
    zip_ = zip_code(k)
    return {
        "format": "madison-case-summary",
        "summaryVersion": SUMMARY_VERSION,
        "schema": jor(get(f, "schema"), SCHEMA),
        "eventCount": len(jor(get(f, "events"), [])),
        "case": {**case_identity(k, zip_, name_of), **case_standing(k, facts, status), **case_ownership(k, printed)},
        "restrictions": restriction_rows(facts.restrictions),
        "conditionalExtensions": conditional_extension_rows(live),
        "violations": violations,
        "snowInspections": snow_inspection_rows(live, k, workspace, name_of),
        "visits": visit_rows(visits, no_of, name_of),
        "documents": document_rows(docs, name_of),
        "corrections": correction_rows(f, name_of),
        "citations": citations,
        "referrals": referral_rows(live, k, name_of),
    }


def plain(value):
    """The value as JSON.stringify would write it: undefined object members omitted, undefined list entries null."""
    if isinstance(value, dict):
        return {k: plain(v) for k, v in value.items() if v is not UNDEF}
    if isinstance(value, list):
        return [None if v is UNDEF else plain(v) for v in value]
    return value


def reportable(summary):
    return {k: v for k, v in summary.items() if k not in METADATA}


def json_text(value):
    """RFC 8785 canonical JSON, the comparison form for summary fields. Python's == treats
    False as 0 and True as 1; JSON and Reports (`k.noticeActive !== false`) do not. Booleans
    stay distinct from numbers at every depth, 197 and 197.0 are the same number, object key
    order is ignored and array order kept. A value JSON cannot represent (non-finite or
    out-of-range numbers, non-JSON types) raises rather than being coerced."""
    return rfc8785.dumps(value)


def same_json(a, b):
    try:
        return json_text(a) == json_text(b)
    except (rfc8785.CanonicalizationError, TypeError, ValueError):
        return False


def projected(record, loaded=False):
    workspace = Workspace(loaded)
    return reportable(plain(project(record, workspace))), workspace.consulted


def used_by_reports(summary):
    """Reports excludes `(summaryVersion ?? version ?? 0) < SUMMARY_VERSION` as an earlier format;
    every other summary reaches report totals and must match its case."""
    version = summary.get("summaryVersion")
    version = summary.get("version") if version is None else version
    version = 0 if version is None else version
    if isinstance(version, str) and re.fullmatch(r"[0-9]+(?:\.[0-9]*)?", version.strip(JS_SPACE)):
        version = float(version.strip(JS_SPACE))
    return not (isinstance(version, (int, float)) and version < SUMMARY_VERSION)


def mismatched_fields(summary, record):
    """Top-level reportable fields where a cached summary differs from the verified case projection.
    Raises when the case cannot be projected (summarize() could not have produced a summary)."""
    actual = reportable(summary)

    def differences(expected):
        return sorted(f for f in set(expected) | set(actual) if f not in actual or f not in expected or not same_json(actual[f], expected[f]))

    expected, ambiguous = projected(record)
    fields = differences(expected)
    if fields and ambiguous:
        alternative = differences(projected(record, loaded=True)[0])
        fields = alternative if len(alternative) < len(fields) else fields
    return fields
