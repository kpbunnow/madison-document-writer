# ---- JavaScript value semantics ----


def get(value, *path):
    """Optional chaining: a missing key or non-object yields undefined."""
    for key in path:
        if isinstance(value, dict):
            value = value.get(key, UNDEF)
        elif isinstance(value, list) and isinstance(key, int) and 0 <= key < len(value):
            value = value[key]
        else:
            return UNDEF
    return value


def truthy(v):
    if v is UNDEF or v is None or v is False:
        return False
    if isinstance(v, (int, float)) and not isinstance(v, bool):
        return v != 0 and not (isinstance(v, float) and math.isnan(v))
    if isinstance(v, str):
        return v != ""
    return True


def jor(*values):
    for v in values[:-1]:
        if truthy(v):
            return v
    return values[-1]


def jand(a, b):
    return b if truthy(a) else a


def jstr(v):
    if v is UNDEF:
        return "undefined"
    if v is None:
        return "null"
    if v is True:
        return "true"
    if v is False:
        return "false"
    if isinstance(v, str):
        return v
    if isinstance(v, (int, float)):
        if isinstance(v, float) and math.isnan(v):
            return "NaN"
        if isinstance(v, float) and v.is_integer() and abs(v) < 1e21:
            return str(int(v))
        return repr(v)
    if isinstance(v, list):
        return ",".join(join_part(x) for x in v)
    return "[object Object]"


def join_part(v):
    return "" if v is UNDEF or v is None else jstr(v)


def jtype(v):
    if v is UNDEF:
        return "undefined"
    if v is None:
        return "null"
    if isinstance(v, bool):
        return "boolean"
    if isinstance(v, (int, float)):
        return "number"
    if isinstance(v, str):
        return "string"
    return "object"


def jeq(a, b):
    """Strict equality (===); objects compare by identity."""
    if jtype(a) != jtype(b):
        return False
    if jtype(a) == "object":
        return a is b
    return a == b


def utf16(text):
    return text.encode("utf-16-be")


def jlt(a, b):
    """The relational < for the values that occur in records: strings by UTF-16 units, numbers numerically."""
    if isinstance(a, str) and isinstance(b, str):
        return utf16(a) < utf16(b)
    if jtype(a) == "number" and jtype(b) == "number":
        return a < b
    return False


def trim(text):
    return text.strip(JS_SPACE)


def jlen(v):
    if isinstance(v, (list, str)):
        return len(v)
    raise TypeError("length of a non-list")


def keys(obj):
    """Object.keys order: integer-like keys ascending, then insertion order."""
    if not isinstance(obj, dict):
        return []
    index = [k for k in obj if re.fullmatch(r"0|[1-9][0-9]{0,9}", k) and int(k) < 2**32 - 1]
    return sorted(index, key=int) + [k for k in obj if k not in index]


def clone(v):
    if v is UNDEF:
        raise TypeError("clone of undefined")
    return json.loads(json.dumps(v))


def items(d):
    v = get(d, "items")
    if not isinstance(v, list):
        raise TypeError("document without items")
    return v


